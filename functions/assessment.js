"use strict";

const {
  RecaptchaEnterpriseServiceClient,
} = require("@google-cloud/recaptcha-enterprise");

/** @type {InstanceType<typeof RecaptchaEnterpriseServiceClient>|undefined} */
let defaultRecaptchaClient;

/**
 * Lazily creates and reuses the reCAPTCHA Enterprise client so repeated
 * assessments do not pay the client construction cost each call.
 *
 * @return {RecaptchaEnterpriseServiceClient} The shared client instance.
 */
function getDefaultRecaptchaClient() {
  if (!defaultRecaptchaClient) {
    defaultRecaptchaClient = new RecaptchaEnterpriseServiceClient();
  }
  return defaultRecaptchaClient;
}

/**
 * Reason classification reported by an assessment risk analysis. Protobuf
 * enums surface as a string or a number, so both are accepted.
 *
 * @typedef {string|number|null} ClassificationReason
 */

/**
 * Token properties reported by the reCAPTCHA Enterprise API. Every field is
 * nullable because the generated client leaves unset fields null.
 *
 * @typedef {Object} TokenProperties
 * @property {?boolean=} valid Whether the token is valid.
 * @property {?string|?number=} invalidReason Why the token was rejected.
 * @property {?string=} action Action the token was generated for.
 */

/**
 * Risk analysis reported by the reCAPTCHA Enterprise API.
 *
 * @typedef {Object} RiskAnalysis
 * @property {?number=} score Risk score in the range [0.0, 1.0].
 * @property {?Array<ClassificationReason>=} reasons Reasons for the score.
 */

/**
 * Assessment response returned by the reCAPTCHA Enterprise API.
 *
 * @typedef {Object} Assessment
 * @property {?TokenProperties=} tokenProperties Token validity details.
 * @property {?RiskAnalysis=} riskAnalysis Risk details for a valid token.
 */

/**
 * Outcome of evaluating an assessment response.
 *
 * @typedef {Object} AssessmentEvaluation
 * @property {boolean} valid Whether the token passed evaluation.
 * @property {?number} score Risk score, or null when not valid.
 * @property {Array<ClassificationReason>} reasons Reasons for the score.
 * @property {?string} reason Failure reason, or null when valid.
 */

/**
 * Assessment request payload accepted by the API.
 *
 * @typedef {Object} AssessmentRequest
 * @property {string} parent Resource path of the project.
 * @property {{event: {token: string, siteKey: string}}} assessment
 *   Assessment to create, holding the client token and site key.
 */

/**
 * Minimal structural surface of RecaptchaEnterpriseServiceClient that this
 * module uses. Declared structurally so unit tests can inject a fake client.
 *
 * @typedef {Object} AssessmentClient
 * @property {(project: string) => string} projectPath Builds a project path.
 * @property {(request?: AssessmentRequest) => Promise<Array<Assessment>>}
 *   createAssessment Creates an assessment; resolves to the response tuple.
 */

/**
 * Options accepted by createAssessment.
 *
 * @typedef {Object} AssessmentOptions
 * @property {string=} projectID Google Cloud project ID.
 * @property {string=} recaptchaKey reCAPTCHA key for the site/app.
 * @property {string=} token Token generated by the client.
 * @property {string=} recaptchaAction Action the token is expected to carry.
 */

/**
 * Builds the reCAPTCHA Enterprise assessment request payload.
 *
 * @param {string} parent Resource path of the project, e.g. projects/{id}.
 * @param {string} recaptchaKey reCAPTCHA key associated with the site/app.
 * @param {string} token Token generated by the client.
 * @return {AssessmentRequest} The assessment request to send to the API.
 */
function buildAssessmentRequest(parent, recaptchaKey, token) {
  return {
    assessment: {
      event: {
        token: token,
        siteKey: recaptchaKey,
      },
    },
    parent: parent,
  };
}

/**
 * Evaluates a reCAPTCHA Enterprise assessment response.
 *
 * @param {Assessment|undefined} response Assessment returned by the API. May
 *   be missing when the API returns no body.
 * @param {string} recaptchaAction Action the token is expected to carry.
 * @return {AssessmentEvaluation} Evaluation result:
 *   {valid, score, reasons, reason}.
 */
function evaluateAssessment(response, recaptchaAction) {
  const tokenProperties = (response && response.tokenProperties) || {};
  if (!tokenProperties.valid) {
    return {
      valid: false,
      score: null,
      reasons: [],
      reason: "The token was: " + tokenProperties.invalidReason,
    };
  }
  if (tokenProperties.action !== recaptchaAction) {
    return {
      valid: false,
      score: null,
      reasons: [],
      reason: "The action attribute in your reCAPTCHA tag does not " +
        "match the action you are expecting to score",
    };
  }
  const riskAnalysis = (response && response.riskAnalysis) || {};
  return {
    valid: true,
    score: typeof riskAnalysis.score === "number" ? riskAnalysis.score : null,
    reasons: riskAnalysis.reasons || [],
    reason: null,
  };
}

/**
 * Creates an assessment to analyze the risk of a UI action.
 *
 * projectID: Your Google Cloud Project ID.
 * recaptchaKey: The reCAPTCHA key associated with the site/app.
 * token: The generated token obtained from the client.
 * recaptchaAction: Action name corresponding to the token.
 *
 * @param {AssessmentOptions} options Assessment options (projectID,
 *   recaptchaKey, token, recaptchaAction).
 * @param {AssessmentClient=} client Optional client override, used by tests.
 * @return {Promise<?number>} The risk score, or null when the token is
 *   invalid or the action does not match.
 */
async function createAssessment({
  projectID = "anychat-c414a",
  recaptchaKey = "****************************************",
  token = "action-token",
  recaptchaAction = "action-name",
}, client) {
  const recaptchaClient = client || getDefaultRecaptchaClient();
  const projectPath = recaptchaClient.projectPath(projectID);

  const request = buildAssessmentRequest(projectPath, recaptchaKey, token);
  const [response] = await recaptchaClient.createAssessment(request);

  const result = evaluateAssessment(response, recaptchaAction);
  if (!result.valid) {
    console.log("The CreateAssessment call failed because " + result.reason);
    return null;
  }

  // For more information on interpreting the assessment, see:
  // https://cloud.google.com/recaptcha-enterprise/docs/interpret-assessment
  console.log(`The reCAPTCHA score is: ${result.score}`);
  result.reasons.forEach((reason) => {
    console.log(reason);
  });

  return result.score;
}

module.exports = {
  buildAssessmentRequest,
  evaluateAssessment,
  createAssessment,
};
